"""Greek additions using original skeletons and this family's own Latin forms."""
from shapely.affinity import affine_transform, scale, translate
from shapely.geometry import box
from shapely.ops import unary_union
from code_symbols import STEMS, SHEAR, _master_glyph, _line, _cubic, _curve, _shear_safe_line


def geometries(weight,italic=False):
    s=STEMS[weight];S=lambda pts:_line(pts,s);C=lambda pts:_curve(pts,s)
    own=lambda ch:_master_glyph(ch,weight,False)
    U=unary_union
    o=own('o')
    d={'ο':o,'ρ':own('p'),'ν':own('v'),'υ':own('u'),'γ':own('y')}
    d['α']=U([o,S([(475,540),(475,70)]),C(_cubic((475,70),(475,25),(510,20),(535,35)))])
    d['β']=U([S([(130,-210),(130,520)]),C(_cubic((130,520),(125,780),(550,730),(450,530))
        +_cubic((450,530),(410,440),(250,385),(170,385))[1:]
        +_cubic((170,385),(600,495),(600,-5),(320,35))[1:]
        +_cubic((320,35),(220,40),(145,115),(130,180))[1:])])
    d['δ']=U([o,C(_cubic((420,515),(345,660),(100,660),(190,745)))])
    d['ε']=C(_cubic((470,475),(140,675),(80,275),(340,270))
        +_cubic((340,270),(100,270),(125,-100),(490,65))[1:])
    d['ζ']=C([(145,510),(470,510)]+_cubic((470,510),(405,440),(105,180),(170,65))[1:]
        +_cubic((170,65),(225,-30),(420,100),(445,-50))[1:]
        +_cubic((445,-50),(455,-115),(390,-180),(305,-180))[1:])
    d['η']=U([own('n'),S([(475,150),(475,-210)])])
    d['θ']=U([own('O'),S([(115,350),(485,350)])])
    d['ι']=C([(270,540),(270,95)]+_cubic((270,95),(270,15),(375,15),(410,60))[1:])
    # Match normal stroke widths after the final italic shear.
    K=lambda pts:_shear_safe_line(pts,s,italic)
    d['κ']=U([K([(135,0),(135,540)]),K([(485,540),(135,245),(495,0)])])
    d['λ']=U([C(_cubic((145,690),(210,720),(265,630),(300,520))),S([(300,520),(510,0)]),S([(310,495),(95,0)])])
    d['μ']=U([own('u'),S([(125,170),(125,-210)])])
    d['ξ']=C(_cubic((455,645),(80,810),(90,345),(415,390))
        +_cubic((415,390),(80,405),(120,35),(355,60))[1:]
        +_cubic((355,60),(550,70),(470,-180),(315,-180))[1:])
    d['π']=U([S([(85,540-s/2),(530,540-s/2)]),S([(180,540),(180,0)]),S([(435,540),(435,90)]+_cubic((435,90),(435,20),(475,20),(510,40))[1:])])
    d['σ']=U([o,S([(290,540-s/2),(545,540-s/2)])])
    d['ς']=C(_cubic((470,460),(115,675),(60,60),(365,45))
        +_cubic((365,45),(585,35),(470,-180),(300,-180))[1:])
    d['τ']=U([S([(90,540-s/2),(510,540-s/2)]),S([(305,535),(305,120)]+_cubic((305,120),(305,20),(395,20),(435,65))[1:])])
    d['φ']=U([o,S([(300,725),(300,-210)])])
    d['χ']=U([K([(115,540),(485,-200)]),K([(485,540),(115,-200)])])
    d['ψ']=U([S([(300,540),(300,-210)]),S([(100,540),(100,260)]+_cubic((100,260),(100,-35),(500,-35),(500,260))[1:]+[(500,540)])])
    d['ω']=C(_cubic((125,515),(15,250),(70,20),(215,s/2))
        +_cubic((215,s/2),(300,35),(310,190),(300,270))[1:]
        +_cubic((300,270),(290,190),(300,35),(385,s/2))[1:]
        +_cubic((385,s/2),(530,20),(585,250),(475,515))[1:])
    d['Δ']=S([(80,s/2),(300,700-s/2),(520,s/2),(80,s/2)])
    d['Σ']=S([(510,700-s/2),(100,700-s/2),(345,350),(100,s/2),(510,s/2)])
    # Open the own O at the baseline, then add horizontal feet.
    omega=own('O').difference(box(150,-60,450,110))
    d['Ω']=U([omega,S([(70,s/2),(240,s/2)]),S([(360,s/2),(530,s/2)])])
    d['Π']=own('П');d['Λ']=S([(85,0),(300,700-s/2),(515,0)])
    d['Φ']=own('Ф');d['Ψ']=U([S([(300,700),(300,0)]),C([(90,700),(90,420)]+_cubic((90,420),(90,140),(510,140),(510,420))[1:]+[(510,700)])])
    d['µ']=d['μ']
    assert set(map(ord,d))==set(range(0x3B1,0x3CA))|set(map(ord,'ΔΣΩΠΛΦΨµ'))
    if italic:
        d={ch:affine_transform(g,[1,SHEAR,0,1,-270*SHEAR,0]) for ch,g in d.items()}
    assert all(g.is_valid and not g.is_empty for g in d.values())
    return d

if __name__=='__main__':
    for w in STEMS:
        for italic in [False,True]:print(w,italic,len(geometries(w,italic)))
